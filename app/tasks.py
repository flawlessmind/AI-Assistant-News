"""Task routing and an evidence-free inventory of data gaps; never a fake LLM answer."""
import re

TASKS=('insight','explain','missing_data','sources')


def task_for(question='',task=None):
    if task and task!='auto':
        if task not in TASKS:
            raise ValueError('Неизвестная задача анализа.')
        return task
    text=question.lower().replace('ё','е')
    if not text.strip():
        return 'insight'
    if re.search(r'не хватает|недостающ|пробел|каки[ех].*данн.*(?:нуж|треб)|чего.*не.*хват',text):
        return 'missing_data'
    if re.search(r'(?:найди|найти|подбери|поищи|дополнительн).*(?:источник|аналитик|исследован)|найти источники',text):
        return 'sources'
    return 'explain'


def industry_segment(profile):
    code=str(profile.get('company',{}).get('industry_okved_code') or '').strip()
    if code.startswith('47.71'):
        return 'clothing'
    if code.startswith('47'):
        return 'retail'
    if code.startswith(('41','42','43')):
        return 'construction'
    if code.startswith('46'):return 'wholesale'
    if code.startswith(('49','50','51','52','53')):return 'transport'
    division=code.split('.')[0]
    if division.isdigit() and 10<=int(division)<=33:return 'manufacturing'
    return 'general'


